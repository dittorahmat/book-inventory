type Row = Record<string, unknown>;

function q(sql: string): Row[] {
  return db.prepare(sql).all() as Row[];
}

function lit(value: unknown): string {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return String(value);
  if (typeof value === "boolean") return value ? "1" : "0";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function insert(table: string, rows: Row[], columns?: string[]): string {
  if (rows.length === 0) return "";
  const cols = columns ?? Object.keys(rows[0]);
  const values = rows
    .map((r) => `(${cols.map((c) => lit(r[c])).join(", ")})`)
    .join(",\n");
  return `INSERT OR IGNORE INTO ${table} (${cols.join(", ")}) VALUES\n${values};\n`;
}

/**
 * Backfill kolom harga untuk baris yang sudah ada di D1.
 * `INSERT OR IGNORE` melewati baris lama, tanpa ini `buy_price`/`sell_price`
 * dan harga paket akan tetap kosong di database yang sudah terisi.
 */
function backfill(
  table: string,
  rows: Row[],
  setColumns: string[],
  whereColumns: string[],
  extraWhere?: string
): string {
  if (rows.length === 0) return "";
  const lines = rows.map((r) => {
    const sets = setColumns.map((c) => `${c} = ${lit(r[c])}`).join(", ");
    const wheres = [
      ...whereColumns.map((c) => `${c} = ${lit(r[c])}`),
      ...(extraWhere ? [extraWhere] : []),
    ].join(" AND ");
    return `UPDATE ${table} SET ${sets} WHERE ${wheres};`;
  });
  return lines.join("\n") + "\n";
}

